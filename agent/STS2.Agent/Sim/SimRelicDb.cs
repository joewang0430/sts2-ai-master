    /// <summary>Index i true ⇔ SimRelicId i overrides DisplayAmount or ShowCounter.</summary>
    private static readonly bool[] _hasCounter = BuildHasCounterTable();

    private static bool[] BuildHasCounterTable()
    {
        var table = new bool[SimRelicId.Count];
        foreach (KeyValuePair<Type, ushort> entry in _byType)
        {
            Type t = entry.Key;
            PropertyInfo displayAmount = t.GetProperty(nameof(RelicModel.DisplayAmount))
                ?? throw new InvalidOperationException($"SimRelicDb: {t.Name}.DisplayAmount not found.");
            PropertyInfo showCounter = t.GetProperty(nameof(RelicModel.ShowCounter))
                ?? throw new InvalidOperationException($"SimRelicDb: {t.Name}.ShowCounter not found.");

            bool overridesDisplayAmount = displayAmount.DeclaringType != typeof(RelicModel);
            bool overridesShowCounter = showCounter.DeclaringType != typeof(RelicModel);
            table[entry.Value] = overridesDisplayAmount || overridesShowCounter;
        }
        return table;
    }

    public static bool TryGetId(Type relicType, out ushort id) => _byType.TryGetValue(relicType, out id);

    public static ushort GetId(Type relicType)
    {
        if (_byType.TryGetValue(relicType, out ushort id))
            return id;

        throw new InvalidOperationException($"SimRelicDb: relic type '{relicType.FullName}' is not registered.");
    }

    public static bool HasCounter(ushort id) => _hasCounter[id];
}
