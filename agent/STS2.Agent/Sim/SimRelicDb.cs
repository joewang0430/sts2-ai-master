/// <see cref="CombatRootRelics"/> and shared by reference across every search node instead of being
/// re-copied per node. Only the ~13% of relics that actually carry a per-combat counter (Kunai,
/// Pen Nib, Nunchaku, etc.) need a slot in the small per-node counter array
/// (<see cref="CombatNodeBlob.RelicCounters"/>) -- the other ~87% are pure static stat modifiers
/// with nothing to track turn to turn.
/// </summary>
