/// <summary>
/// Static <c>Type -&gt; SimRelicId</c> lookup table, built the same way as <c>SimCardDb</c>. Also
/// classifies each relic as "counter-bearing" or not -- i.e. whether it overrides
/// <see cref="RelicModel.DisplayAmount"/> or <see cref="RelicModel.ShowCounter"/> beyond the base
/// class's always-0/always-false defaults. Unlike the Power/Enchantment/Affliction registries, this
/// classification does not need a hand-maintained table: it is derived once via reflection at
/// class-init time, since it only depends on each relic <em>type</em> (not on live game content
